-- TOTAL CUSTOMERS
SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUST FROM Bank_Departure

-- EXIT CUSTOMERS
SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUST FROM Bank_Departure
WHERE EXITED = 1

-- RETAIN CUSTOMERS
SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUST FROM Bank_Departure
WHERE EXITED = 0

-- CHURN %

WITH CTE AS (
SELECT  (SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUST FROM Bank_Departure) AS TOTAL_CUST,
(SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUST FROM Bank_Departure
WHERE EXITED = 1 ) AS EXITED_CUST)
SELECT ROUND( (EXITED_CUST * 100.0 / TOTAL_CUST),2) AS CHURN_RATE  FROM CTE


-- RETAIN %
WITH CTE AS (
SELECT  (SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUST FROM Bank_Departure) AS TOTAL_CUST,
(SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUST FROM Bank_Departure
WHERE EXITED = 0 ) AS RETAIN_CUST)
SELECT ROUND( (RETAIN_CUST * 100.0 / TOTAL_CUST),2) AS CHURN_RATE  FROM CTE


-- AVERAGE CREDIT SCORE
SELECT AVG(CREDITSCORE) AS AVG_CREDTI_SCORE FROM Bank_Departure


-- EXIT CUSTOMER BY CREDITSCORE CATEGORY 

SELECT COUNT(CUSTOMERID) AS TOTAL_CUST, CSCATEGORY FROM 
(SELECT *,
CASE 
WHEN CREDITSCORE >= 800 AND CREDITSCORE <= 850 THEN 'EXCELLENT'
WHEN CREDITSCORE >= 740 AND CREDITSCORE <= 799 THEN 'VERY GOOD'
WHEN CREDITSCORE >= 670 AND CREDITSCORE <= 739 THEN 'GOOD'
WHEN CREDITSCORE >= 580 AND CREDITSCORE <= 669 THEN 'FAIR'
WHEN CREDITSCORE >= 300 AND CREDITSCORE <= 579 THEN 'POOR'
END
AS CSCATEGORY
FROM BANK_DEPARTURE
) AS A
WHERE EXITED = 1
GROUP BY CSCATEGORY

-- which age customers are exiting the most
WITH AGE_GROUP 
AS (
SELECT CUSTOMERID,AGE,EXITED,
CASE
WHEN AGE>=18 AND AGE<=30 THEN '18-30'
WHEN AGE>=31 AND AGE<= 45 THEN '31-45'
WHEN AGE>=46 AND AGE<= 60 THEN '46-60'
WHEN AGE>= 61 AND AGE<= 75 THEN '61-75'
WHEN AGE>75 THEN '76++'
END
AS AGE_GROUP 
FROM Bank_Departure
)
SELECT COUNT(CUSTOMERID),AGE_GROUP FROM AGE_GROUP
WHERE EXITED = 1
GROUP BY AGE_GROUP 

--EXIT CUSTOMERS BY CREDIT CARD CATEGORY

SELECT COUNT(B.CUSTOMERID), C.CATEGORY
FROM Bank_Departure B
INNER JOIN CreditCard C
ON B.HasCrCard = C.CreditID
WHERE B.Exited = 1
GROUP BY C.CATEGORY


